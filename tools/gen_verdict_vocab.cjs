#!/usr/bin/env node
'use strict';
// Generates widget/widgetAssets/js/fsrPbVerdictVocab.js from the canonical
// verdict-vocabulary.json that lives in the widget harness. The widget ships as
// standalone AngularJS and cannot read JSON at runtime, so the codes it needs
// are emitted as a static asset instead of being typed in by hand.
//
//   node tools/gen_verdict_vocab.cjs          regenerate the asset
//   node tools/gen_verdict_vocab.cjs --check  exit 1 when the asset is stale
//
// The canonical file is <harness>/tests/live/lib/verdict-vocabulary.json, where
// <harness> is $FSR_WIDGET_HARNESS or the fortisoar-widget-harness checkout next
// to this repo's widgets-src/ directory.

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const ASSET = path.join(REPO_ROOT, 'widget', 'widgetAssets', 'js', 'fsrPbVerdictVocab.js');
const CANONICAL_REL = path.join('tests', 'live', 'lib', 'verdict-vocabulary.json');

function canonicalPath() {
  const root = process.env.FSR_WIDGET_HARNESS
    ? path.resolve(process.env.FSR_WIDGET_HARNESS)
    : path.resolve(REPO_ROOT, '..', '..', 'fortisoar-widget-harness');
  return path.join(root, CANONICAL_REL);
}

// The asset carries only what the widget reads. Adding a field the widget
// needs means adding it here and regenerating; the parity test fails until then.
function render(vocab) {
  const codes = (vocab.notAnError && vocab.notAnError.codes) || [];
  return [
    '/* GENERATED by tools/gen_verdict_vocab.cjs from verdict-vocabulary.json',
    ' * (version ' + vocab.version + '). Do not edit by hand: change the canonical file and',
    ' * regenerate. tests/approval.parkedOutcome.test.js fails while this is stale. */',
    '(function () {',
    '    window.FsrPbVerdictVocab = {',
    '        version: ' + vocab.version + ',',
    '        // notAnError.codes: ok:false payloads that mean PARKED, not failed.',
    '        parkedCodes: ' + JSON.stringify(codes),
    '    };',
    '})();',
    ''
  ].join('\n');
}

function main() {
  const canonical = canonicalPath();
  if (!fs.existsSync(canonical)) {
    console.error('canonical vocabulary not found: ' + canonical +
      ' (set FSR_WIDGET_HARNESS to the harness checkout)');
    process.exit(2);
  }
  const text = render(JSON.parse(fs.readFileSync(canonical, 'utf8')));
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(ASSET) ? fs.readFileSync(ASSET, 'utf8') : '';
    if (current !== text) {
      console.error('stale: ' + ASSET + ' (run node tools/gen_verdict_vocab.cjs)');
      process.exit(1);
    }
    console.log('up to date: ' + ASSET);
    return;
  }
  fs.writeFileSync(ASSET, text);
  console.log('wrote ' + ASSET);
}

if (require.main === module) main();

module.exports = { render, canonicalPath, ASSET };
